"""AI 탐험 퀴즈 게임의 시작점(entry point).

이 파일에는 실행에 꼭 필요한 두 단계만 둔다.
1. ``QuizGame`` 객체를 만든다.
2. 객체의 ``run()`` 메서드로 메뉴 반복을 시작한다.

실제 기능을 다른 파일에 나누면 이 파일은 '어디서 시작하는가'만 보여 주므로
초보자도 프로그램의 첫 실행 흐름을 쉽게 찾을 수 있다.
"""

from quiz_game import QuizGame


def main() -> None:
    """게임 객체를 생성하고 전체 실행 흐름을 시작한다.

    ``QuizGame()``을 만드는 순간 ``__init__``이 실행되어 저장 데이터를 읽고,
    이어서 ``run()``이 메뉴를 반복해서 보여 준다.
    """
    QuizGame().run()


# 이 조건은 이 파일을 ``python main.py``로 직접 실행했을 때만 참이다.
# 다른 파일이 ``import main``을 해도 게임이 저절로 시작되지 않게 막아 준다.
if __name__ == "__main__":
    main()
